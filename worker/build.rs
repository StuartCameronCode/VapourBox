//! Compiles the add-on manifests (`app/assets/addons/*.json`) into the worker,
//! so the app and the worker read the same files: one source of truth for
//! what each add-on is and what an install of it holds (see `src/addons.rs`).

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let crate_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let dir = crate_dir.join("..").join("app").join("assets").join("addons");
    // A directory: Cargo rescans it, so adding a manifest rebuilds too.
    println!("cargo:rerun-if-changed={}", dir.display());

    // Git keeps no empty directory, so none at all means no manifests.
    let mut manifests: Vec<PathBuf> = fs::read_dir(&dir)
        .into_iter()
        .flatten()
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    manifests.sort();

    let mut out = String::from(
        "/// Every add-on manifest, as (file name, contents). Generated by build.rs.\n\
         pub(crate) const MANIFESTS: &[(&str, &str)] = &[\n",
    );
    for path in &manifests {
        println!("cargo:rerun-if-changed={}", path.display());
        let name = path.file_name().unwrap().to_string_lossy().to_string();
        let abs = fs::canonicalize(path).unwrap();
        out.push_str(&format!(
            "    ({name:?}, include_str!({:?})),\n",
            abs.to_string_lossy()
        ));
    }
    out.push_str("];\n");
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("addon_manifests.rs");
    fs::write(dest, out).unwrap();
}
