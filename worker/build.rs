//! Compiles the add-on manifests (`app/assets/addons/*.json`) into the worker,
//! so the app and the worker read the same files: one source of truth for
//! what each add-on is and what an install of it holds (see `src/addons.rs`).
//! Also compiles in the output capability table
//! (`Tests/TestResources/output_capabilities.json`, task #49), after checking
//! its shape, so a malformed table fails the build rather than a job.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let crate_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let dir = crate_dir.join("..").join("app").join("assets").join("addons");
    // A directory: Cargo rescans it, so adding a manifest rebuilds too.
    println!("cargo:rerun-if-changed={}", dir.display());

    // Git keeps no empty directory, so none at all means no manifests.
    let mut manifests: Vec<PathBuf> = fs::read_dir(&dir)
        .into_iter()
        .flatten()
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    manifests.sort();

    let mut out = String::from(
        "/// Every add-on manifest, as (file name, contents). Generated by build.rs.\n\
         pub(crate) const MANIFESTS: &[(&str, &str)] = &[\n",
    );
    for path in &manifests {
        println!("cargo:rerun-if-changed={}", path.display());
        let name = path.file_name().unwrap().to_string_lossy().to_string();
        let abs = fs::canonicalize(path).unwrap();
        out.push_str(&format!(
            "    ({name:?}, include_str!({:?})),\n",
            abs.to_string_lossy()
        ));
    }
    out.push_str("];\n");
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("addon_manifests.rs");
    fs::write(dest, out).unwrap();

    output_capabilities(&crate_dir);
}

/// Checks the output capability table's shape and writes
/// `output_capabilities.rs`: the file's text, for `models::output_capabilities`
/// to parse into its typed rows (whose enum names only the crate knows).
fn output_capabilities(crate_dir: &std::path::Path) {
    let path = crate_dir.join("..").join("Tests").join("TestResources").join("output_capabilities.json");
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let table: serde_json::Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let fail = |what: String| -> ! { panic!("{}: {what}", path.display()) };
    let array = |key: &str| {
        table[key].as_array().cloned().unwrap_or_else(|| fail(format!("`{key}` must be an array")))
    };
    for row in array("containers") {
        for (key, is_bool) in [
            ("container", false),
            ("storesStreamStart", true),
            ("videoTimeBase", false),
            ("fieldFlag", true),
            ("audioPacketTiming", false),
            ("restoredPassthrough", false),
            ("subtitles", false),
            ("isoMedia", true),
        ] {
            let ok = if is_bool { row[key].is_boolean() } else { row[key].is_string() };
            if !ok {
                fail(format!("container row {row} needs `{key}`"));
            }
        }
    }
    for row in array("video") {
        let verdict = row["verdict"].as_str().unwrap_or_default();
        if !["offered", "notOffered", "refused"].contains(&verdict) {
            fail(format!("video row {row}: verdict must be offered, notOffered or refused"));
        }
        if !row["codec"].is_string() || !row["container"].is_string() {
            fail(format!("video row {row} needs `codec` and `container`"));
        }
        if row["message"].is_string() == (verdict == "offered") {
            fail(format!("video row {row}: a message exactly when not offered"));
        }
    }
    for row in array("audioConvert") {
        let supported = row["supported"].as_bool().unwrap_or_else(|| fail(format!("{row}: `supported`")));
        if row["message"].is_string() == supported {
            fail(format!("audioConvert row {row}: a message exactly when unsupported"));
        }
    }
    let copy = table["audioCopy"].as_object().unwrap_or_else(|| fail("`audioCopy` must be an object".into()));
    if copy.values().any(|v| !v.as_array().is_some_and(|a| a.iter().all(|c| c.is_string()))) {
        fail("`audioCopy` maps each container to codec names".into());
    }
    if !table["audioCopyMessage"].is_string() {
        fail("`audioCopyMessage` must be a string".into());
    }
    let abs = fs::canonicalize(&path).unwrap();
    let out = format!(
        "/// Tests/TestResources/output_capabilities.json. Generated by build.rs.\n\
         pub(crate) const TABLE_JSON: &str = include_str!({:?});\n",
        abs.to_string_lossy()
    );
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("output_capabilities.rs");
    fs::write(dest, out).unwrap();
}
