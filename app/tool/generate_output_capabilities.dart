/// Writes `lib/models/output_capabilities_table.dart` from
/// `Tests/TestResources/output_capabilities.json` (task #49), so the app reads
/// the same table the worker compiles in (`worker/build.rs`) without loading
/// an asset: every check that reads it is synchronous and runs in unit tests.
///
/// Run from `app/` after editing the JSON:
///
///     dart run tool/generate_output_capabilities.dart
///
/// `output_capabilities_table_test.dart` regenerates it in memory and fails on
/// any difference.
library;

import 'dart:convert';
import 'dart:io';

const tablePath = '../Tests/TestResources/output_capabilities.json';
const outputPath = 'lib/models/output_capabilities_table.dart';

void main() {
  File(outputPath).writeAsStringSync(generate(File(tablePath).readAsStringSync()));
  stdout.writeln('wrote $outputPath');
}

String _lit(Object? v) {
  if (v is String) return jsonEncode(v).replaceAll(r'$', r'\$');
  if (v is bool || v is num) return '$v';
  if (v == null) return 'null';
  throw ArgumentError('unexpected value $v');
}

/// The generated Dart source for the table's JSON text.
String generate(String json) {
  final t = jsonDecode(json) as Map<String, dynamic>;
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/generate_output_capabilities.dart from')
    ..writeln('// Tests/TestResources/output_capabilities.json. Do not edit: change the')
    ..writeln('// JSON and run `dart run tool/generate_output_capabilities.dart` in app/')
    ..writeln('// (and don\'t `dart format` it: the freshness test compares it as written).')
    ..writeln('// Read through `video_job.dart` / `encoding_settings.dart` (task #49).')
    ..writeln()
    ..writeln('/// Each container\'s traits, by `ContainerFormat.value`.')
    ..writeln('const outputContainerTraits = <String, Map<String, Object>>{');
  for (final row in (t['containers'] as List).cast<Map<String, dynamic>>()) {
    b.writeln('  ${_lit(row['container'])}: {');
    for (final e in row.entries.where((e) => e.key != 'container')) {
      b.writeln('    ${_lit(e.key)}: ${_lit(e.value)},');
    }
    b.writeln('  },');
  }
  b
    ..writeln('};')
    ..writeln()
    ..writeln('/// One row per video codec (`VideoCodec.value`) and container:')
    ..writeln('/// (verdict, message, muxEncoder, ffmpegWrites).')
    ..writeln('const outputVideoRows = <(String, String), (String, String?, String?, bool)>{');
  for (final row in (t['video'] as List).cast<Map<String, dynamic>>()) {
    b.writeln('  (${_lit(row['codec'])}, ${_lit(row['container'])}): '
        '(${_lit(row['verdict'])}, ${_lit(row['message'])}, '
        '${_lit(row['muxEncoder'])}, ${_lit(row['ffmpegWrites'] ?? false)}),');
  }
  b
    ..writeln('};')
    ..writeln()
    ..writeln('/// Convert: one row per `AudioCodec.value` and container: (supported, message).')
    ..writeln('const outputAudioConvertRows = <(String, String), (bool, String?)>{');
  for (final row in (t['audioConvert'] as List).cast<Map<String, dynamic>>()) {
    b.writeln('  (${_lit(row['codec'])}, ${_lit(row['container'])}): '
        '(${_lit(row['supported'])}, ${_lit(row['message'])}),');
  }
  b
    ..writeln('};')
    ..writeln()
    ..writeln('/// Passthrough: the ffprobe `codec_name`s each container takes as a copy.')
    ..writeln('const outputAudioCopy = <String, Set<String>>{');
  for (final e in (t['audioCopy'] as Map<String, dynamic>).entries) {
    b.writeln('  ${_lit(e.key)}: {');
    for (final c in (e.value as List)) {
      b.writeln('    ${_lit(c)},');
    }
    b.writeln('  },');
  }
  b
    ..writeln('};')
    ..writeln()
    ..writeln('/// The copy refusal, with `{codec}`, `{container}` and `{containers}`.')
    ..writeln('const outputAudioCopyMessage =')
    ..writeln('    ${_lit(t['audioCopyMessage'])};');
  return b.toString();
}
